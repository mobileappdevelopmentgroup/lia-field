#!/usr/bin/env bash
# Rehearses the LIVE apply of 33 (published part sets): a database built to
# look like production — 01–32, umbrella-shaped, with records and a published
# parts list in it — then 33 pasted on top, twice, the way the SQL editor runs
# it. run.sh is a different test: it builds everything from empty.
#
# Three things it proves, beyond "it ran":
#
#   * NOTHING ALREADY THERE CHANGES. Every existing table is fingerprinted
#     before and after. 33 adds a table and three functions; if a row anywhere
#     else moved, that is a bug in the paste, not a feature of it.
#   * The re-emitted consolidate_to_one_account() still refuses while accounts
#     sit under an umbrella — on the live database it would otherwise merge
#     Nate's and Michael's companies.
#   * Sets work against production-shaped accounts in both directions: down
#     from Batavia, never sideways between subcontractors.
#
# Also writes the paste-able bundle, supabase/dist/apply-33.sql (generated,
# not committed — rebuild it rather than keep one around).
#
#   ./supabase/test/run-apply-33.sh
set -euo pipefail

DB="${LIA_TEST_DB:-lia_apply33}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
MIG="$SUPA/migrations"

for p in /opt/homebrew/opt/postgresql@16/bin /opt/homebrew/bin /usr/local/bin; do
  [ -d "$p" ] && PATH="$p:$PATH"
done

pg_isready -q || { echo "No local Postgres. Try: brew services start postgresql@16" >&2; exit 1; }

# ── The bundle ──────────────────────────────────────────────────────────────
mkdir -p "$SUPA/dist"
BUNDLE="$SUPA/dist/apply-33.sql"
{
  cat <<'HDR'
-- ═══════════════════════════════════════════════════════════════════
-- Lia — migration 33, published part sets, as one paste.
--
-- GENERATED by supabase/test/run-apply-33.sh, which rehearsed it against a
-- production-shaped database before writing it. Do not edit by hand; edit
-- supabase/migrations/33_published_part_sets.sql and regenerate.
--
-- Needs 01–32 already applied (27's account_parts, 18's can_use_catalog,
-- 26's require_lead_account, 30's consolidate_to_one_account).
--
-- Adds account_part_sets, save_account_part_sets(), account_part_sets_catalog()
-- and re-emits consolidate_to_one_account() with one block added. Changes no
-- existing row. Idempotent: running it twice is safe.
--
-- Check afterwards from outside, with the publishable key:
--   POST /rest/v1/rpc/account_part_sets_catalog  →  401 (exists, anon refused)
-- ═══════════════════════════════════════════════════════════════════

HDR
  cat "$MIG/33_published_part_sets.sql"
} > "$BUNDLE"

# ── A database standing where production stands ────────────────────────────
echo "Rebuilding '$DB' at migration 32, the way production stands…"
psql -q -d postgres -c "DROP DATABASE IF EXISTS $DB;" -c "CREATE DATABASE $DB;"
run() { psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$1" >/dev/null; }

run "$HERE/00_stub_supabase.sql"
# 10 is skipped, as it was on the live database (see build-combined.sh): it is
# the optional single-company consolidation, re-emitted later by 29 and 30.
for f in "$MIG"/0[1-9]_*.sql "$MIG"/1[1-9]_*.sql "$MIG"/2[0-9]_*.sql "$MIG"/3[0-2]_*.sql; do
  run "$f"
done

echo "Seeding a production-shaped umbrella…"
psql -q -v ON_ERROR_STOP=1 -d "$DB" >/dev/null <<'SQL'
INSERT INTO auth.users(id,email) VALUES
  ('b0000000-0000-0000-0000-000000000001','office@batavia.test'),
  ('b0000000-0000-0000-0000-000000000002','nate@sub.test'),
  ('b0000000-0000-0000-0000-000000000003','michael@sub.test'),
  ('b0000000-0000-0000-0000-000000000004','crew@nate.test') ON CONFLICT DO NOTHING;
DO $$
DECLARE v_umb uuid; v_nate uuid;
BEGIN
  v_umb  := create_lia_user('b0000000-0000-0000-0000-000000000001','office@batavia.test','Batavia',-1,NULL,'lead','001');
  v_nate := create_subcontractor('b0000000-0000-0000-0000-000000000002','nate@sub.test','Nate','763', v_umb);
  PERFORM create_subcontractor('b0000000-0000-0000-0000-000000000003','michael@sub.test','Michael','738', v_umb);
  PERFORM create_lia_user('b0000000-0000-0000-0000-000000000004','crew@nate.test','Crew',0, v_nate,'tech');
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-1","work_order_id":"WO-PROD"}'::jsonb);
SELECT record_inspection('{"serial_num":"PROD-2","work_order_id":"WO-PROD"}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
SELECT save_account_parts('{"parts":[
  {"part_number":"G13","favorited":true,"default_qty":2,"ord":1},
  {"part_number":"W44","favorited":true,"ord":2}]}'::jsonb);
SQL

# Every public table, every row, as one hash per table.
fingerprint() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" <<'SQL'
DO $$
DECLARE r record; h text;
BEGIN
  CREATE TEMP TABLE IF NOT EXISTS _fp(tbl text PRIMARY KEY, hash text);
  TRUNCATE _fp;
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> 'account_part_sets'
            ORDER BY 1 LOOP
    EXECUTE format('SELECT md5(coalesce(string_agg(t::text, %L ORDER BY t::text), %L)) FROM public.%I t',
                   E'\n', '', r.relname) INTO h;
    INSERT INTO _fp VALUES (r.relname, h);
  END LOOP;
END $$;
SELECT tbl || ' ' || hash FROM _fp ORDER BY tbl;
SQL
}

BEFORE="$(fingerprint)"
echo "  fingerprinted $(echo "$BEFORE" | wc -l | tr -d ' ') existing tables"

for pass in 1 2; do
  echo
  echo "Applying apply-33.sql as one paste — pass ${pass}…"
  psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$BUNDLE" >/dev/null
  echo "  applied cleanly"
done

AFTER="$(fingerprint)"
echo
if [ "$BEFORE" != "$AFTER" ]; then
  echo "FAIL: applying 33 changed existing data:" >&2
  diff <(echo "$BEFORE") <(echo "$AFTER") >&2 || true
  exit 1
fi
echo "ok  no existing row in any table changed"

echo
echo "Checking the result…"
psql -v ON_ERROR_STOP=1 -v helpers="$HERE/_helpers.sql" -q -d "$DB" <<'SQL'
\i :helpers
-- The consolidation refusal, as the operator would meet it.
DO $$ BEGIN
  PERFORM pg_temp.want_error('consolidation still refuses on an umbrella database',
    $q$ SELECT consolidate_to_one_account('b0000000-0000-0000-0000-000000000001') $q$);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000002';   -- Nate
SELECT save_account_part_sets('{"sets":[{"name":"Ford plant","parts":["G13","W44"]}]}'::jsonb);
DO $$ BEGIN
  PERFORM pg_temp.want('a lead can publish a set',
    (SELECT parts FROM account_part_sets_catalog() WHERE name = 'Ford plant'), '["G13","W44"]'::jsonb);
  PERFORM pg_temp.want('and the parts list from before is untouched by it',
    (SELECT count(*)::int FROM account_parts_catalog() WHERE NOT is_deleted), 2);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000001';   -- Batavia
SELECT save_account_part_sets('{"sets":[{"name":"Batavia standard","parts":["G13"]}]}'::jsonb);

SET lia.uid = 'b0000000-0000-0000-0000-000000000004';   -- Nate's crew
DO $$ BEGIN
  PERFORM pg_temp.want('Nate''s crew gets Nate''s set and Batavia''s',
    (SELECT string_agg(name, ',' ORDER BY NOT mine, name) FROM account_part_sets_catalog()),
    'Ford plant,Batavia standard');
  PERFORM pg_temp.want_error('and cannot publish',
    $q$ SELECT save_account_part_sets('{"sets":[]}'::jsonb) $q$);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000003';   -- Michael
DO $$ BEGIN
  PERFORM pg_temp.want('Michael sees Batavia''s set and never Nate''s',
    (SELECT string_agg(name, ',') FROM account_part_sets_catalog()), 'Batavia standard');
END $$;

RESET lia.uid;
SET ROLE anon;
DO $$ BEGIN
  PERFORM pg_temp.want_error('anon cannot call the catalogue',
    $q$ SELECT * FROM account_part_sets_catalog() $q$);
  PERFORM pg_temp.want_error('nor read the table', $q$ SELECT count(*) FROM account_part_sets $q$);
END $$;
RESET ROLE;
SQL

echo
echo "Rehearsal passed. Bundle: $BUNDLE ($(wc -l < "$BUNDLE" | tr -d ' ') lines)"
echo "Inspect with: psql -d $DB"
echo "Drop with:    psql -d postgres -c 'DROP DATABASE $DB;'"
