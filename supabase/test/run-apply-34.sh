#!/usr/bin/env bash
# Rehearses the LIVE apply of 34 (vehicle inventory): a database built to look
# like production — 01–33, umbrella-shaped, with ladder records, parts and a
# published set in it — then 34 pasted on top, twice, the way the SQL editor
# runs it. run.sh is a different test: it builds everything from empty.
#
# Three things it proves, beyond "it ran":
#
#   * NOTHING ALREADY THERE CHANGES. Every existing table is fingerprinted
#     before and after. 34 adds tables, functions and a trigger on inspections;
#     if a row anywhere else moved, that is a bug in the paste.
#   * The re-emitted consolidate_to_one_account() still refuses while accounts
#     sit under an umbrella — on the live database it would otherwise merge
#     Nate's and Michael's companies.
#   * Inventory works against production-shaped accounts: Batavia sees Nate's
#     trucks, Michael never does, and recording a ladder still works with the
#     new trigger on inspections — with deduction off, and on.
#
# Also writes the paste-able bundle, supabase/dist/apply-34.sql (generated,
# not committed — rebuild it rather than keep one around).
#
#   ./supabase/test/run-apply-34.sh
set -euo pipefail

DB="${LIA_TEST_DB:-lia_apply34}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
MIG="$SUPA/migrations"

for p in /opt/homebrew/opt/postgresql@16/bin /opt/homebrew/bin /usr/local/bin; do
  [ -d "$p" ] && PATH="$p:$PATH"
done

pg_isready -q || { echo "No local Postgres. Try: brew services start postgresql@16" >&2; exit 1; }

# ── The bundle ──────────────────────────────────────────────────────────────
mkdir -p "$SUPA/dist"
BUNDLE="$SUPA/dist/apply-34.sql"
{
  cat <<'HDR'
-- ═══════════════════════════════════════════════════════════════════
-- Lia — migration 34, vehicle inventory, as one paste.
--
-- GENERATED by supabase/test/run-apply-34.sh, which rehearsed it against a
-- production-shaped database before writing it. Do not edit by hand; edit
-- supabase/migrations/34_vehicle_inventory.sql and regenerate.
--
-- Needs 01–33 already applied (18's can_see, 26's require_lead_account,
-- 33's consolidate_to_one_account and part sets).
--
-- Adds the stock_* tables and functions, a deferred trigger on inspections
-- (ladder parts off the truck — OFF until the office switches it on), revokes
-- anon from 33's objects, and re-emits consolidate_to_one_account() with one
-- block added. Changes no existing row. Idempotent: running it twice is safe.
--
-- Check afterwards from outside, with the publishable key:
--   POST /rest/v1/rpc/my_vehicles                →  401 (exists, anon refused)
--   POST /rest/v1/rpc/account_part_sets_catalog  →  401 (anon now revoked)
-- ═══════════════════════════════════════════════════════════════════

HDR
  cat "$MIG/34_vehicle_inventory.sql"
} > "$BUNDLE"

# ── A database standing where production stands ────────────────────────────
echo "Rebuilding '$DB' at migration 33, the way production stands…"
psql -q -d postgres -c "DROP DATABASE IF EXISTS $DB;" -c "CREATE DATABASE $DB;"
run() { psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$1" >/dev/null; }

run "$HERE/00_stub_supabase.sql"
# 10 is skipped, as it was on the live database (see build-combined.sh): it is
# the optional single-company consolidation, re-emitted later by 29 and 30.
for f in "$MIG"/0[1-9]_*.sql "$MIG"/1[1-9]_*.sql "$MIG"/2[0-9]_*.sql "$MIG"/3[0-3]_*.sql; do
  run "$f"
done

echo "Seeding a production-shaped umbrella…"
psql -q -v ON_ERROR_STOP=1 -d "$DB" >/dev/null <<'SQL'
INSERT INTO auth.users(id,email) VALUES
  ('b0000000-0000-0000-0000-000000000001','office@batavia.test'),
  ('b0000000-0000-0000-0000-000000000002','nate@sub.test'),
  ('b0000000-0000-0000-0000-000000000003','michael@sub.test'),
  ('b0000000-0000-0000-0000-000000000004','crew@nate.test') ON CONFLICT DO NOTHING;
DO $$
DECLARE v_umb uuid; v_nate uuid;
BEGIN
  v_umb  := create_lia_user('b0000000-0000-0000-0000-000000000001','office@batavia.test','Batavia',-1,NULL,'lead','001');
  v_nate := create_subcontractor('b0000000-0000-0000-0000-000000000002','nate@sub.test','Nate','763', v_umb);
  PERFORM create_subcontractor('b0000000-0000-0000-0000-000000000003','michael@sub.test','Michael','738', v_umb);
  PERFORM create_lia_user('b0000000-0000-0000-0000-000000000004','crew@nate.test','Crew',0, v_nate,'tech');
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-1","work_order_id":"WO-PROD"}'::jsonb);
SELECT record_inspection('{"serial_num":"PROD-2","work_order_id":"WO-PROD"}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
SELECT save_account_parts('{"parts":[
  {"part_number":"G13","favorited":true,"default_qty":2,"ord":1},
  {"part_number":"W44","favorited":true,"ord":2}]}'::jsonb);
SELECT save_account_part_sets('{"sets":[{"name":"Ford plant","parts":["G13","W44"]}]}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-3","work_order_id":"WO-PROD","parts":[{"name":"G13","qty":2}]}'::jsonb);
SQL

# Every public table, every row, as one hash per table.
fingerprint() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" <<'SQL'
DO $$
DECLARE r record; h text;
BEGIN
  CREATE TEMP TABLE IF NOT EXISTS _fp(tbl text PRIMARY KEY, hash text);
  TRUNCATE _fp;
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname NOT LIKE 'stock_%'
            ORDER BY 1 LOOP
    EXECUTE format('SELECT md5(coalesce(string_agg(t::text, %L ORDER BY t::text), %L)) FROM public.%I t',
                   E'\n', '', r.relname) INTO h;
    INSERT INTO _fp VALUES (r.relname, h);
  END LOOP;
END $$;
SELECT tbl || ' ' || hash FROM _fp ORDER BY tbl;
SQL
}

BEFORE="$(fingerprint)"
echo "  fingerprinted $(echo "$BEFORE" | wc -l | tr -d ' ') existing tables"

for pass in 1 2; do
  echo
  echo "Applying apply-34.sql as one paste — pass ${pass}…"
  psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$BUNDLE" >/dev/null
  echo "  applied cleanly"
done

AFTER="$(fingerprint)"
echo
if [ "$BEFORE" != "$AFTER" ]; then
  echo "FAIL: applying 34 changed existing data:" >&2
  diff <(echo "$BEFORE") <(echo "$AFTER") >&2 || true
  exit 1
fi
echo "ok  no existing row in any table changed"

echo
echo "Checking the result…"
psql -v ON_ERROR_STOP=1 -v helpers="$HERE/_helpers.sql" -q -d "$DB" <<'SQL'
\i :helpers
DO $$ BEGIN
  PERFORM pg_temp.want_error('consolidation still refuses on an umbrella database',
    $q$ SELECT consolidate_to_one_account('b0000000-0000-0000-0000-000000000001') $q$);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000002';   -- Nate sets up a truck
SELECT save_stock_location('{"name":"Truck 1"}'::jsonb);
SELECT set_stock_assignees((SELECT id FROM stock_locations WHERE name = 'Truck 1'),
                           ARRAY['b0000000-0000-0000-0000-000000000004'::uuid]);
SELECT adjust_stock(jsonb_build_object('location_id', (SELECT id FROM stock_locations WHERE name = 'Truck 1'),
  'reason', 'load', 'part_number', 'G13', 'qty', 10));

SET lia.uid = 'b0000000-0000-0000-0000-000000000004';   -- his crew, deduction OFF
SELECT record_inspection('{"serial_num":"PROD-4","work_order_id":"WO-PROD","parts":[{"name":"G13","qty":1}]}'::jsonb);
DO $$ BEGIN
  PERFORM pg_temp.want('a ladder still records with the new trigger, and takes nothing while off',
    (SELECT qty FROM stock_levels WHERE part_key = 'G13'), 10);
  PERFORM pg_temp.want('the crew sees their truck', json_array_length(my_vehicles()->'vehicles'), 1);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
SELECT save_stock_settings('{"auto_deduct":true}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-5","work_order_id":"WO-PROD","parts":[{"name":"G13","qty":2}]}'::jsonb);
DO $$ BEGIN
  PERFORM pg_temp.want('switched on, a new ladder''s parts come off the truck',
    (SELECT qty FROM stock_levels WHERE part_key = 'G13'), 8);
  PERFORM pg_temp.want('and nothing is taken for ladders recorded before it was on',
    (SELECT count(*)::int FROM stock_moves WHERE reason = 'ladder'), 1);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000001';   -- Batavia
DO $$ BEGIN
  PERFORM pg_temp.want('the umbrella sees the subcontractor''s truck',
    json_array_length(stock_overview()->'locations'), 1);
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000003';   -- Michael
DO $$ BEGIN
  PERFORM pg_temp.want('a sibling does not', json_array_length(stock_overview()->'locations'), 0);
END $$;

RESET lia.uid;
SET ROLE anon;
DO $$ BEGIN
  PERFORM pg_temp.want_error('anon cannot call the phone''s read', $q$ SELECT my_vehicles() $q$);
  PERFORM pg_temp.want_error('nor 33''s catalogue any more', $q$ SELECT * FROM account_part_sets_catalog() $q$);
  PERFORM pg_temp.want_error('nor read the ledger', $q$ SELECT count(*) FROM stock_moves $q$);
END $$;
RESET ROLE;
SQL

echo
echo "Rehearsal passed. Bundle: $BUNDLE ($(wc -l < "$BUNDLE" | tr -d ' ') lines)"
echo "Inspect with: psql -d $DB"
echo "Drop with:    psql -d postgres -c 'DROP DATABASE $DB;'"
