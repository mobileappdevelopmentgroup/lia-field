SQL

# Every public table, every row, as one hash per table.
fingerprint() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" <<'SQL'
DO $$
DECLARE r record; h text;
BEGIN
  CREATE TEMP TABLE IF NOT EXISTS _fp(tbl text PRIMARY KEY, hash text);
  TRUNCATE _fp;
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname NOT LIKE 'stock_%'
            ORDER BY 1 LOOP
    EXECUTE format('SELECT md5(coalesce(string_agg((to_jsonb(t) - %L)::text, %L ORDER BY (to_jsonb(t) - %L)::text), %L)) FROM public.%I t',
                   'mfr_serial', E'\n', 'mfr_serial', '', r.relname) INTO h;
    INSERT INTO _fp VALUES (r.relname, h);
  END LOOP;
END $$;
SELECT tbl || ' ' || hash FROM _fp ORDER BY tbl;
SQL
}

BEFORE="$(fingerprint)"
echo "  fingerprinted $(echo "$BEFORE" | wc -l | tr -d ' ') existing tables"

for pass in 1 2; do
  echo
  echo "Applying apply-37.sql as one paste — pass ${pass}…"
  psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$BUNDLE" >/dev/null
  echo "  applied cleanly"
done

AFTER="$(fingerprint)"
echo
if [ "$BEFORE" != "$AFTER" ]; then
  echo "FAIL: applying 37 changed existing data:" >&2
  diff <(echo "$BEFORE") <(echo "$AFTER") >&2 || true
  exit 1
fi
echo "ok  no existing row in any table changed"

echo
echo "Checking the result…"
psql -v ON_ERROR_STOP=1 -v helpers="$HERE/_helpers.sql" -q -d "$DB" <<'SQL'
\i :helpers
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';   -- Nate loads his sheet
DO $$
DECLARE v json;
BEGIN
  v := add_fp_serial_pool('{"source":"Lia Office: defective no tags nate sheet 1.csv",
    "used":["FP161282","FP161340"],"serials":["FP161347","FP161348","FP161349"]}'::jsonb);
  PERFORM pg_temp.want('free / on an item / spent on the sheet / out of tag stock',
    (v->>'added') || '/' || (v->>'already_on_an_item') || '/' || (v->>'used_on_sheet') || '/' || (v->>'taken_from_tag_stock'),
    '3/1/1/4');
  PERFORM pg_temp.want('no blank tag is left for those numbers',
    (SELECT count(*)::int FROM fp_tag_stock WHERE source = 'import:nate-google-sheets-2026-09-28'), 0);
  PERFORM pg_temp.want('the summary counts 36''s pool and the sheet together',
    (SELECT (s->>'free') || '/' || (s->>'reserved') || '/' || (s->>'used') FROM (SELECT fp_serial_pool_summary() s) x),
    '4/1/2');
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000004';   -- his crew's phone
DO $$ BEGIN
  PERFORM pg_temp.want('the phone keeps what it held and is given only free numbers',
    (SELECT string_agg(serial, ',' ORDER BY serial) FROM reserve_fp_serials(20)), 'FP161347,FP161348,FP161349,UT-1,UT-2');
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000003';   -- Michael
DO $$ BEGIN
  PERFORM pg_temp.want('a sibling gets none of them', (SELECT count(*)::int FROM reserve_fp_serials(5)), 0);
END $$;

RESET lia.uid;
SET ROLE anon;
DO $$ BEGIN
  PERFORM pg_temp.want_error('anon cannot load', $q$ SELECT add_fp_serial_pool('{}'::jsonb) $q$);
  PERFORM pg_temp.want_error('nor reserve', $q$ SELECT * FROM reserve_fp_serials(1) $q$);
END $$;
RESET ROLE;
SQL

echo
echo "Rehearsal passed. Bundle: $BUNDLE ($(wc -l < "$BUNDLE" | tr -d ' ') lines)"
echo "Inspect with: psql -d $DB"
echo "Drop with:    psql -d postgres -c 'DROP DATABASE $DB;'"
