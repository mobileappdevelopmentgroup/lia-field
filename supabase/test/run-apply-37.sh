#!/usr/bin/env bash
# Rehearses the LIVE apply of 37 (spare numbers that are also tags): a
# database built to look like production — 01–36, umbrella-shaped, with Nate's
# 2026-09-28 sheet import as it really landed (an item carrying FP161282 as its
# TAG LABEL, blank tags in stock) and some numbers already in the pool — then
# 37 pasted on top, twice, the way the SQL editor runs it.
#
# What it proves, beyond "it ran":
#
#   * NOTHING ALREADY THERE CHANGES. Every table is fingerprinted before and
#     after. 37 replaces functions, a trigger and an index; it touches no row.
#   * Then Nate's sheet, loaded the way Lia Office sends it: the tagged item's
#     number goes in used, the sheet's spent numbers go in used, the blanks
#     leave tag stock, and a phone is given only the free ones.
#
# Also writes the paste-able bundle, supabase/dist/apply-37.sql (generated,
# not committed — rebuild it rather than keep one around).
#
#   ./supabase/test/run-apply-37.sh
set -euo pipefail

DB="${LIA_TEST_DB:-lia_apply37}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
MIG="$SUPA/migrations"

for p in /opt/homebrew/opt/postgresql@16/bin /opt/homebrew/bin /usr/local/bin; do
  [ -d "$p" ] && PATH="$p:$PATH"
done

pg_isready -q || { echo "No local Postgres. Try: brew services start postgresql@16" >&2; exit 1; }

# ── The bundle ──────────────────────────────────────────────────────────────
mkdir -p "$SUPA/dist"
BUNDLE="$SUPA/dist/apply-37.sql"
{
  cat <<'HDR'
-- ═══════════════════════════════════════════════════════════════════
-- Lia — migration 37, spare numbers that are also tags, as one paste.
--
-- GENERATED by supabase/test/run-apply-37.sh, which rehearsed it against a
-- production-shaped database before writing it. Do not edit by hand; edit
-- supabase/migrations/37_fp_serial_pool_tags.sql and regenerate.
--
-- Needs 01–36 already applied.
--
-- Replaces add_fp_serial_pool() (now takes the sheet's spent numbers as
-- `used`, finds a number carried as a tag label, and takes loaded numbers out
-- of blank tag stock), reserve_fp_serials() and fp_serial_pool_summary() (a
-- number spent on the sheet is not free), and the trigger on assets (a number
-- given as a tag label is used). Anon revoked. Changes no existing row.
-- Idempotent.
--
-- Check afterwards from outside, with the publishable key:
--   POST /rest/v1/rpc/add_fp_serial_pool  →  401 42501 (exists, anon refused)
-- ═══════════════════════════════════════════════════════════════════

HDR
  cat "$MIG/37_fp_serial_pool_tags.sql"
} > "$BUNDLE"

# ── A database standing where production stands ────────────────────────────
echo "Rebuilding '$DB' at migration 36, the way production stands…"
psql -q -d postgres -c "DROP DATABASE IF EXISTS $DB;" -c "CREATE DATABASE $DB;"
run() { psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$1" >/dev/null; }

run "$HERE/00_stub_supabase.sql"
# 10 is skipped, as it was on the live database (see build-combined.sh).
for f in "$MIG"/0[1-9]_*.sql "$MIG"/1[1-9]_*.sql "$MIG"/2[0-9]_*.sql "$MIG"/3[0-6]_*.sql; do
  run "$f"
done

echo "Seeding a production-shaped umbrella…"
psql -q -v ON_ERROR_STOP=1 -d "$DB" >/dev/null <<'SQL'
INSERT INTO auth.users(id,email) VALUES
  ('b0000000-0000-0000-0000-000000000001','office@batavia.test'),
  ('b0000000-0000-0000-0000-000000000002','nate@sub.test'),
  ('b0000000-0000-0000-0000-000000000003','michael@sub.test'),
  ('b0000000-0000-0000-0000-000000000004','crew@nate.test') ON CONFLICT DO NOTHING;
DO $$
DECLARE v_umb uuid; v_nate uuid;
BEGIN
  v_umb  := create_lia_user('b0000000-0000-0000-0000-000000000001','office@batavia.test','Batavia',-1,NULL,'lead','001');
  v_nate := create_subcontractor('b0000000-0000-0000-0000-000000000002','nate@sub.test','Nate','763', v_umb);
  PERFORM create_subcontractor('b0000000-0000-0000-0000-000000000003','michael@sub.test','Michael','738', v_umb);
  PERFORM create_lia_user('b0000000-0000-0000-0000-000000000004','crew@nate.test','Crew',0, v_nate,'tech');
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-1","work_order_id":"WO-PROD"}'::jsonb);
SELECT record_inspection('{"serial_num":"PROD-2","work_order_id":"WO-PROD"}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
SELECT save_account_parts('{"parts":[
  {"part_number":"G13","favorited":true,"default_qty":2,"ord":1},
  {"part_number":"W44","favorited":true,"ord":2}]}'::jsonb);
SELECT save_account_part_sets('{"sets":[{"name":"Ford plant","parts":["G13","W44"]}]}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-3","work_order_id":"WO-PROD","parts":[{"name":"G13","qty":2}]}'::jsonb);
-- Fall protection as Nate's 2026-09-28 import really landed: the number on
-- the TAG LABEL (the serial is the manufacturer's), and blank tags in stock.
INSERT INTO assets (account_id, kind, serial_raw, serial_key, tag_label)
SELECT account_id, 'fall_protection', '8291761', serial_key('8291761'), 'FP161282'
  FROM account_members WHERE user_id = 'b0000000-0000-0000-0000-000000000002';
INSERT INTO fp_tag_stock (account_id, tag_label, tag_url, source)
SELECT account_id, 'FP1613' || n, 'https://docs.google.com/spreadsheets/d/x' || n || '/edit',
       'import:nate-google-sheets-2026-09-28'
  FROM account_members, unnest(ARRAY['40','47','48','49']) n
 WHERE user_id = 'b0000000-0000-0000-0000-000000000002';
-- And a pool loaded under 36, one number held by a phone.
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
SELECT add_fp_serial_pool('{"source":"36","serials":["UT-1","UT-2"]}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
