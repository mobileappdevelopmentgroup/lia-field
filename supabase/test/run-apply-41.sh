#!/usr/bin/env bash
# Rehearses the LIVE apply of 41 (training and test accounts) on a database
# built to look like production — 01–40, umbrella-shaped, field ladders and an
# FP item under Nate, a certificate view recorded — then the paste on top,
# twice, the way the SQL editor runs it.
#
#   * NOTHING ALREADY THERE CHANGES. Every table is fingerprinted before and
#     after (ignoring the new, defaulted training columns on accounts).
#   * Every public view answers exactly what it answered before, row for row.
#   * The new unfiltered views and service-role functions are closed to anon.
#
# Writes the paste-able bundle, supabase/dist/apply-41.sql (generated, not
# committed).
#
#   ./supabase/test/run-apply-41.sh
set -euo pipefail

DB="${LIA_TEST_DB:-lia_apply41}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
MIG="$SUPA/migrations"

for p in /opt/homebrew/opt/postgresql@16/bin /opt/homebrew/bin /usr/local/bin; do
  [ -d "$p" ] && PATH="$p:$PATH"
done

pg_isready -q || { echo "No local Postgres. Try: brew services start postgresql@16" >&2; exit 1; }

mkdir -p "$SUPA/dist"
BUNDLE="$SUPA/dist/apply-41.sql"
{
  cat <<'HDR'
-- ═══════════════════════════════════════════════════════════════════
-- Lia — migration 41: training and test accounts.
--
-- GENERATED by supabase/test/run-apply-41.sh, which rehearsed it against
-- a production-shaped database before writing it. Do not edit by hand.
--
-- Needs 01–40 already applied. Changes no existing row (adds defaulted
-- columns to accounts). Idempotent. Every public view keeps its columns and
-- grants and answers the same rows: no account is a training account yet.
--
-- Check afterwards from outside, with the publishable key:
--   GET  /rest/v1/ladder_inspections_public?select=serial_num&limit=1  → 200, as before
--   GET  /rest/v1/ladder_inspections_all?select=serial_num&limit=1     → 401 42501
--   GET  /rest/v1/rpc/training_ladder_inspections?p_token=x            → 200 []
--   POST /rest/v1/rpc/training_erase {"p_actor":null,"p_account":null} → 401 42501
--   GET  /rest/v1/training_erasures?select=id                          → 401 42501
-- ═══════════════════════════════════════════════════════════════════

HDR
  cat "$MIG/41_training_accounts.sql"
} > "$BUNDLE"

echo "Rebuilding '$DB' at migration 40, the way production stands…"
psql -q -d postgres -c "DROP DATABASE IF EXISTS $DB;" -c "CREATE DATABASE $DB;"
run() { psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$1" >/dev/null; }

run "$HERE/00_stub_supabase.sql"
psql -q -d "$DB" -c "DO \$\$ BEGIN CREATE ROLE service_role NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END \$\$;" >/dev/null
# 10 is skipped, as it was on the live database (see build-combined.sh).
for f in "$MIG"/0[1-9]_*.sql "$MIG"/1[1-9]_*.sql "$MIG"/2[0-9]_*.sql "$MIG"/3[0-9]_*.sql "$MIG"/40_*.sql; do
  run "$f"
done

echo "Seeding a production-shaped umbrella…"
psql -q -v ON_ERROR_STOP=1 -d "$DB" >/dev/null <<'SQL'
INSERT INTO auth.users(id,email) VALUES
  ('b0000000-0000-0000-0000-000000000001','office@batavia.test'),
  ('b0000000-0000-0000-0000-000000000002','nate@sub.test'),
  ('b0000000-0000-0000-0000-000000000003','michael@sub.test'),
  ('b0000000-0000-0000-0000-000000000004','crew@nate.test') ON CONFLICT DO NOTHING;
DO $$
DECLARE v_umb uuid; v_nate uuid;
BEGIN
  v_umb  := create_lia_user('b0000000-0000-0000-0000-000000000001','office@batavia.test','Batavia',-1,NULL,'lead','001');
  v_nate := create_subcontractor('b0000000-0000-0000-0000-000000000002','nate@sub.test','Nate','763', v_umb);
  PERFORM create_subcontractor('b0000000-0000-0000-0000-000000000003','michael@sub.test','Michael','738', v_umb);
  PERFORM create_lia_user('b0000000-0000-0000-0000-000000000004','crew@nate.test','Crew',0, v_nate,'tech');
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-1","work_order_id":"WO-PROD","source":"field","brand":"Werner","parts":[{"name":"G13","qty":2}]}'::jsonb);
SELECT record_inspection('{"serial_num":"1135318","work_order_id":"WO-PROD","source":"field","parts":[{"name":"PMCD4","qty":1}]}'::jsonb);
SELECT record_inspection('{"serial_num":"PROD-OLD","work_order_id":"WO-PROD","source":"office"}'::jsonb);
SELECT record_fp_inspection(jsonb_build_object('serial_num','FP-PROD-1','manufacturer','MSA','model','V-FIT',
  'checks', jsonb_build_array(jsonb_build_object('prompt','Labels?','result',false))));
RESET lia.uid;
SELECT record_certificate_view('{"serial_key":"PROD-1","user_agent":"Mozilla/5.0 (Macintosh)"}'::jsonb);
SQL

# Every public table, every row, as one hash per table.
fingerprint() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" <<'SQL'
DO $$
DECLARE r record; h text;
BEGIN
  CREATE TEMP TABLE IF NOT EXISTS _fp(tbl text PRIMARY KEY, hash text);
  TRUNCATE _fp;
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname NOT LIKE 'stock_%'
            ORDER BY 1 LOOP
    EXECUTE format('SELECT md5(coalesce(string_agg((to_jsonb(t) - %L::text[])::text, %L ORDER BY (to_jsonb(t) - %L::text[])::text), %L)) FROM public.%I t',
                   '{is_training,training_expires_at,training_bsi_work_orders,training_preview_token,training_created_by}', E'\n',
                   '{is_training,training_expires_at,training_bsi_work_orders,training_preview_token,training_created_by}', '', r.relname) INTO h;
    INSERT INTO _fp VALUES (r.relname, h);
  END LOOP;
END $$;
SELECT tbl || ' ' || hash FROM _fp ORDER BY tbl;
SQL
}

views() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" -c "SET ROLE anon;
    SELECT md5(string_agg(to_jsonb(v)::text, E'\\n' ORDER BY to_jsonb(v)::text)) FROM ladder_inspections_public v
    UNION ALL SELECT md5(string_agg((to_jsonb(v) - 'tag_url_key')::text, E'\\n' ORDER BY (to_jsonb(v) - 'tag_url_key')::text)) FROM fall_protection_public v
    UNION ALL SELECT md5(string_agg(to_jsonb(v)::text, E'\\n' ORDER BY to_jsonb(v)::text)) FROM fall_protection_checks_public v;"
}
VIEWS_BEFORE="$(views)"
BEFORE="$(fingerprint)"
echo "  fingerprinted $(echo "$BEFORE" | wc -l | tr -d ' ') existing tables"

for pass in 1 2; do
  echo
  echo "Applying apply-41.sql as one paste — pass ${pass}…"
  psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$BUNDLE" >/dev/null
  echo "  applied cleanly"
done

# Only tables that existed before; 41's own new table starts empty.
AFTER="$(fingerprint | grep -v '^training_erasures ')"
echo
if [ "$BEFORE" != "$AFTER" ]; then
  echo "FAIL: applying 41 changed existing data:" >&2
  diff <(echo "$BEFORE") <(echo "$AFTER") >&2 || true
  exit 1
fi
echo "ok  no existing row in any table changed"
if [ "$VIEWS_BEFORE" != "$(views)" ]; then
  echo "FAIL: a public view answers differently after 41" >&2; exit 1
fi
echo "ok  every public view answers exactly as before, row for row"

echo
echo "Checking the result…"
psql -v ON_ERROR_STOP=1 -v helpers="$HERE/_helpers.sql" -q -d "$DB" <<'SQL'
\i :helpers
SET ROLE anon;
SELECT pg_temp.want('the public ladder view keeps every column, in place',
  (SELECT string_agg(column_name::text, ',' ORDER BY ordinal_position) FROM information_schema.columns
    WHERE table_name = 'ladder_inspections_public'),
  'serial_num,serial_key,inspection_date,tech_name,rep_name,rep_number,verified_by,next_due_date,work_order_id,notes,brand,type,length,created_at,public_ref,version,lubricated,has_leveler,has_claw,has_vrung,certificate_url,destroyed,destroy_reason,tag_label,tag_label_key');
SELECT pg_temp.want('the destroyed ladder still reads destroyed',
  (SELECT destroyed FROM ladder_inspections_public WHERE serial_num = '1135318'), true);
SELECT pg_temp.want('the failed FP item is still public with its check',
  (SELECT count(*) FROM fall_protection_checks_public)::int, 1);
SELECT pg_temp.want('a made-up preview token answers nothing',
  (SELECT count(*) FROM training_ladder_inspections(repeat('a', 64)))::int, 0);
DO $$ BEGIN
  PERFORM pg_temp.want_error('anon cannot read the unfiltered view', $q$ SELECT 1 FROM ladder_inspections_all $q$);
  PERFORM pg_temp.want_error('anon cannot erase', $q$ SELECT training_erase(NULL, NULL) $q$);
  PERFORM pg_temp.want_error('anon cannot read the erasure log', $q$ SELECT 1 FROM training_erasures $q$);
END $$;
RESET ROLE;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT pg_temp.want('a real crew member is not in training',
  (my_context()->>'is_training')::boolean, false);
SELECT record_inspection('{"serial_num":"PROD-4","work_order_id":"WO-PROD","source":"field"}'::jsonb);
SELECT pg_temp.want('real field work still goes public at once',
  (SELECT count(*) FROM ladder_inspections_public WHERE serial_num = 'PROD-4')::int, 1);
SQL

echo
echo "Rehearsal passed. Bundle: $BUNDLE ($(wc -l < "$BUNDLE" | tr -d ' ') lines)"
echo "Inspect with: psql -d $DB"
echo "Drop with:    psql -d postgres -c 'DROP DATABASE $DB;'"
