#!/usr/bin/env bash
# Rehearses the LIVE apply of 35 (fall-protection history import): a database
# built to look like production — 01–34, umbrella-shaped, with ladder records,
# a field FP record and a record from Nate's 2026-09-28 sheet import — then 35
# pasted on top, twice, the way the SQL editor runs it.
#
# What it proves, beyond "it ran":
#
#   * NOTHING ALREADY THERE CHANGES. Every existing table is fingerprinted
#     before and after, minus the one column 35 adds (fp_inspections.mfr_serial,
#     NULL on every existing row).
#   * An import lands in the importing lead's own account and a crew phone in
#     that account downloads it (account_snapshot); a sibling never sees it.
#   * Undo cannot reach Nate's sheet import, and a clash with field work is
#     skipped, not superseded.
#
# Also writes the paste-able bundle, supabase/dist/apply-35.sql (generated,
# not committed — rebuild it rather than keep one around).
#
#   ./supabase/test/run-apply-35.sh
set -euo pipefail

DB="${LIA_TEST_DB:-lia_apply35}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
MIG="$SUPA/migrations"

for p in /opt/homebrew/opt/postgresql@16/bin /opt/homebrew/bin /usr/local/bin; do
  [ -d "$p" ] && PATH="$p:$PATH"
done

pg_isready -q || { echo "No local Postgres. Try: brew services start postgresql@16" >&2; exit 1; }

# ── The bundle ──────────────────────────────────────────────────────────────
mkdir -p "$SUPA/dist"
BUNDLE="$SUPA/dist/apply-35.sql"
{
  cat <<'HDR'
-- ═══════════════════════════════════════════════════════════════════
-- Lia — migration 35, fall-protection history import, as one paste.
--
-- GENERATED by supabase/test/run-apply-35.sh, which rehearsed it against a
-- production-shaped database before writing it. Do not edit by hand; edit
-- supabase/migrations/35_fp_history_import.sql and regenerate.
--
-- Needs 01–34 already applied (26's require_lead_account).
--
-- Adds fp_inspections.mfr_serial (NULL on every existing row), an index, and
-- import_fp_history(), undo_fp_history_import(), fp_history_imports() — lead
-- only, anon revoked. Changes no existing row. Idempotent.
--
-- Check afterwards from outside, with the publishable key:
--   POST /rest/v1/rpc/import_fp_history   →  401 42501 (exists, anon refused)
-- ═══════════════════════════════════════════════════════════════════

HDR
  cat "$MIG/35_fp_history_import.sql"
} > "$BUNDLE"

# ── A database standing where production stands ────────────────────────────
echo "Rebuilding '$DB' at migration 34, the way production stands…"
psql -q -d postgres -c "DROP DATABASE IF EXISTS $DB;" -c "CREATE DATABASE $DB;"
run() { psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$1" >/dev/null; }

run "$HERE/00_stub_supabase.sql"
# 10 is skipped, as it was on the live database (see build-combined.sh).
for f in "$MIG"/0[1-9]_*.sql "$MIG"/1[1-9]_*.sql "$MIG"/2[0-9]_*.sql "$MIG"/3[0-4]_*.sql; do
  run "$f"
done

echo "Seeding a production-shaped umbrella…"
psql -q -v ON_ERROR_STOP=1 -d "$DB" >/dev/null <<'SQL'
INSERT INTO auth.users(id,email) VALUES
  ('b0000000-0000-0000-0000-000000000001','office@batavia.test'),
  ('b0000000-0000-0000-0000-000000000002','nate@sub.test'),
  ('b0000000-0000-0000-0000-000000000003','michael@sub.test'),
  ('b0000000-0000-0000-0000-000000000004','crew@nate.test') ON CONFLICT DO NOTHING;
DO $$
DECLARE v_umb uuid; v_nate uuid;
BEGIN
  v_umb  := create_lia_user('b0000000-0000-0000-0000-000000000001','office@batavia.test','Batavia',-1,NULL,'lead','001');
  v_nate := create_subcontractor('b0000000-0000-0000-0000-000000000002','nate@sub.test','Nate','763', v_umb);
  PERFORM create_subcontractor('b0000000-0000-0000-0000-000000000003','michael@sub.test','Michael','738', v_umb);
  PERFORM create_lia_user('b0000000-0000-0000-0000-000000000004','crew@nate.test','Crew',0, v_nate,'tech');
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-1","work_order_id":"WO-PROD"}'::jsonb);
SELECT record_inspection('{"serial_num":"PROD-2","work_order_id":"WO-PROD"}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
SELECT save_account_parts('{"parts":[
  {"part_number":"G13","favorited":true,"default_qty":2,"ord":1},
  {"part_number":"W44","favorited":true,"ord":2}]}'::jsonb);
SELECT save_account_part_sets('{"sets":[{"name":"Ford plant","parts":["G13","W44"]}]}'::jsonb);
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-3","work_order_id":"WO-PROD","parts":[{"name":"G13","qty":2}]}'::jsonb);
-- Fall protection as production has it: a field record, and one from the
-- 2026-09-28 sheet import.
INSERT INTO assets (account_id, kind, serial_raw, serial_key)
SELECT account_id, 'fall_protection', s, serial_key(s)
  FROM account_members, unnest(ARRAY['FP-FIELD-1','FP161282']) s
 WHERE user_id = 'b0000000-0000-0000-0000-000000000002';
INSERT INTO fp_inspections (account_id, asset_id, inspection_date, overall_pass, source, captured_at)
SELECT a.account_id, a.id, '2026-09-01', true,
       CASE a.serial_raw WHEN 'FP161282' THEN 'import:nate-google-sheets-2026-09-28' ELSE 'field' END,
       CASE a.serial_raw WHEN 'FP161282' THEN NULL ELSE '2026-09-01T14:00:00Z'::timestamptz END
  FROM assets a WHERE a.kind = 'fall_protection';
SQL

# Every public table, every row, as one hash per table.
fingerprint() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" <<'SQL'
DO $$
DECLARE r record; h text;
BEGIN
  CREATE TEMP TABLE IF NOT EXISTS _fp(tbl text PRIMARY KEY, hash text);
  TRUNCATE _fp;
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname NOT LIKE 'stock_%'
            ORDER BY 1 LOOP
    -- (to_jsonb(t) - 'mfr_serial'): the one column 35 adds, NULL everywhere.
    EXECUTE format('SELECT md5(coalesce(string_agg((to_jsonb(t) - %L)::text, %L ORDER BY (to_jsonb(t) - %L)::text), %L)) FROM public.%I t',
                   'mfr_serial', E'\n', 'mfr_serial', '', r.relname) INTO h;
    INSERT INTO _fp VALUES (r.relname, h);
  END LOOP;
END $$;
SELECT tbl || ' ' || hash FROM _fp ORDER BY tbl;
SQL
}

BEFORE="$(fingerprint)"
echo "  fingerprinted $(echo "$BEFORE" | wc -l | tr -d ' ') existing tables"

for pass in 1 2; do
  echo
  echo "Applying apply-35.sql as one paste — pass ${pass}…"
  psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$BUNDLE" >/dev/null
  echo "  applied cleanly"
done

AFTER="$(fingerprint)"
echo
if [ "$BEFORE" != "$AFTER" ]; then
  echo "FAIL: applying 35 changed existing data:" >&2
  diff <(echo "$BEFORE") <(echo "$AFTER") >&2 || true
  exit 1
fi
echo "ok  no existing row in any table changed"

echo
echo "Checking the result…"
psql -v ON_ERROR_STOP=1 -v helpers="$HERE/_helpers.sql" -q -d "$DB" <<'SQL'
\i :helpers
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';   -- Nate imports his history
DO $$
DECLARE v json;
BEGIN
  v := import_fp_history(jsonb_build_object('batch', '2026-10-14 rehearsal', 'rows', jsonb_build_array(
    jsonb_build_object('row', 2, 'serial', 'BAT-5001', 'inspection_date', '2025-06-01', 'result', 'pass',
                       'equipment_type', 'body_harness', 'mfr_serial', 'MSA-1'),
    jsonb_build_object('row', 3, 'serial', 'FP-FIELD-1', 'inspection_date', '2026-09-01', 'result', 'fail'))));
  PERFORM pg_temp.want('the new item imports', (v->>'imported')::int, 1);
  PERFORM pg_temp.want('the clash with field work is skipped',
    (SELECT (s->>'row')::int FROM json_array_elements(v->'skipped') s), 3);
  PERFORM pg_temp.want('the field record is untouched',
    (SELECT count(*)::int FROM fp_inspections i JOIN assets a ON a.id = i.asset_id
      WHERE a.serial_raw = 'FP-FIELD-1' AND i.is_current AND i.source = 'field' AND i.overall_pass), 1);
  PERFORM pg_temp.want_error('undo cannot reach the sheet import',
    $q$ SELECT undo_fp_history_import('nate-google-sheets-2026-09-28') $q$);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000004';   -- his crew's phone
DO $$ BEGIN
  PERFORM pg_temp.want('the crew''s phone downloads the imported item',
    (SELECT last_inspected || ' ' || next_due FROM account_snapshot() WHERE serial_key = 'BAT5001'),
    '2025-06-01 2026-06-01');
  PERFORM pg_temp.want_error('and a tech cannot import', $q$ SELECT import_fp_history('{"batch":"x","rows":[]}'::jsonb) $q$);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000003';   -- Michael
DO $$ BEGIN
  PERFORM pg_temp.want('a sibling''s phone does not',
    (SELECT count(*)::int FROM account_snapshot() WHERE serial_key = 'BAT5001'), 0);
END $$;

SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
DO $$
DECLARE v json;
BEGIN
  v := undo_fp_history_import('2026-10-14 rehearsal');
  PERFORM pg_temp.want('undo removes it again', (v->>'records_removed')::int, 1);
  PERFORM pg_temp.want('and leaves the sheet import alone',
    (SELECT count(*)::int FROM fp_inspections WHERE source = 'import:nate-google-sheets-2026-09-28'), 1);
END $$;

RESET lia.uid;
SET ROLE anon;
DO $$ BEGIN
  PERFORM pg_temp.want_error('anon cannot import', $q$ SELECT import_fp_history('{}'::jsonb) $q$);
  PERFORM pg_temp.want_error('nor list', $q$ SELECT * FROM fp_history_imports() $q$);
END $$;
RESET ROLE;
SQL

echo
echo "Rehearsal passed. Bundle: $BUNDLE ($(wc -l < "$BUNDLE" | tr -d ' ') lines)"
echo "Inspect with: psql -d $DB"
echo "Drop with:    psql -d postgres -c 'DROP DATABASE $DB;'"
