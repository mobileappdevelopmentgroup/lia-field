#!/usr/bin/env bash
# Rehearses the LIVE apply of 38 (office adds a ladder; FP corrections follow
# an impersonation session): a database built to look like production — 01–37,
# umbrella-shaped, with field ladders and a harness under Nate — then 38 pasted
# on top, twice, the way the SQL editor runs it.
#
#   * NOTHING ALREADY THERE CHANGES. Every table is fingerprinted before and
#     after. 38 replaces four functions and one CHECK constraint.
#   * Then Batavia's office, acting as Nate, corrects his harness and adds a
#     ladder to his work order — both land in his account.
#
# Also writes the paste-able bundle, supabase/dist/apply-38.sql (generated,
# not committed).
#
#   ./supabase/test/run-apply-38.sh
set -euo pipefail

DB="${LIA_TEST_DB:-lia_apply38}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
MIG="$SUPA/migrations"

for p in /opt/homebrew/opt/postgresql@16/bin /opt/homebrew/bin /usr/local/bin; do
  [ -d "$p" ] && PATH="$p:$PATH"
done

pg_isready -q || { echo "No local Postgres. Try: brew services start postgresql@16" >&2; exit 1; }

mkdir -p "$SUPA/dist"
BUNDLE="$SUPA/dist/apply-38.sql"
{
  cat <<'HDR'
-- ═══════════════════════════════════════════════════════════════════
-- Lia — migration 38, office adds a ladder / FP corrections while acting,
-- as one paste.
--
-- GENERATED by supabase/test/run-apply-38.sh, which rehearsed it against a
-- production-shaped database before writing it. Do not edit by hand; edit
-- supabase/migrations/38_field_work_edits.sql and regenerate.
--
-- Needs 01–37 already applied.
--
-- Adds add_inspection_office(); re-emits amend/delete/restore_fp_inspection
-- with require_lead_account(); lets inspection_audit record 'add'. Anon
-- revoked. Changes no existing row. Idempotent.
--
-- Check afterwards from outside, with the publishable key:
--   POST /rest/v1/rpc/add_inspection_office  →  401 42501 (exists, anon refused)
-- ═══════════════════════════════════════════════════════════════════

HDR
  cat "$MIG/38_field_work_edits.sql"
} > "$BUNDLE"

echo "Rebuilding '$DB' at migration 37, the way production will stand…"
psql -q -d postgres -c "DROP DATABASE IF EXISTS $DB;" -c "CREATE DATABASE $DB;"
run() { psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$1" >/dev/null; }

run "$HERE/00_stub_supabase.sql"
# 10 is skipped, as it was on the live database (see build-combined.sh).
for f in "$MIG"/0[1-9]_*.sql "$MIG"/1[1-9]_*.sql "$MIG"/2[0-9]_*.sql "$MIG"/3[0-7]_*.sql; do
  run "$f"
done

echo "Seeding a production-shaped umbrella…"
psql -q -v ON_ERROR_STOP=1 -d "$DB" >/dev/null <<'SQL'
INSERT INTO auth.users(id,email) VALUES
  ('b0000000-0000-0000-0000-000000000001','office@batavia.test'),
  ('b0000000-0000-0000-0000-000000000002','nate@sub.test'),
  ('b0000000-0000-0000-0000-000000000003','michael@sub.test'),
  ('b0000000-0000-0000-0000-000000000004','crew@nate.test') ON CONFLICT DO NOTHING;
DO $$
DECLARE v_umb uuid; v_nate uuid;
BEGIN
  v_umb  := create_lia_user('b0000000-0000-0000-0000-000000000001','office@batavia.test','Batavia',-1,NULL,'lead','001');
  v_nate := create_subcontractor('b0000000-0000-0000-0000-000000000002','nate@sub.test','Nate','763', v_umb);
  PERFORM create_subcontractor('b0000000-0000-0000-0000-000000000003','michael@sub.test','Michael','738', v_umb);
  PERFORM create_lia_user('b0000000-0000-0000-0000-000000000004','crew@nate.test','Crew',0, v_nate,'tech');
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-1","work_order_id":"WO-PROD","source":"field","brand":"Werner"}'::jsonb);
SELECT record_inspection('{"serial_num":"PROD-2","work_order_id":"WO-PROD","source":"field"}'::jsonb);
SELECT record_fp_inspection(jsonb_build_object(
  'serial_num', 'PROD-H1', 'equipment_type', 'climbing_belt', 'work_order_id', 'WO-PROD',
  'checks', (SELECT jsonb_agg(jsonb_build_object('code', c.code, 'answer', c.pass_answer))
               FROM fp_template_checks c
               JOIN fp_check_templates t ON t.id = c.template_id
               JOIN fp_equipment_types e ON e.id = t.equipment_type_id
              WHERE e.slug = 'climbing_belt' AND e.account_id IS NULL
                AND t.published_at IS NOT NULL)));
SET lia.uid = 'b0000000-0000-0000-0000-000000000002';
SELECT amend_inspection(jsonb_build_object('inspection_id',
  (SELECT id FROM inspections WHERE serial_num = 'PROD-1' AND is_current), 'reason', 'brand', 'brand', 'Louisville'));
SQL

# Every public table, every row, as one hash per table.
fingerprint() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" <<'SQL'
DO $$
DECLARE r record; h text;
BEGIN
  CREATE TEMP TABLE IF NOT EXISTS _fp(tbl text PRIMARY KEY, hash text);
  TRUNCATE _fp;
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname NOT LIKE 'stock_%'
            ORDER BY 1 LOOP
    EXECUTE format('SELECT md5(coalesce(string_agg((to_jsonb(t) - %L)::text, %L ORDER BY (to_jsonb(t) - %L)::text), %L)) FROM public.%I t',
                   'mfr_serial', E'\n', 'mfr_serial', '', r.relname) INTO h;
    INSERT INTO _fp VALUES (r.relname, h);
  END LOOP;
END $$;
SELECT tbl || ' ' || hash FROM _fp ORDER BY tbl;
SQL
}

BEFORE="$(fingerprint)"
echo "  fingerprinted $(echo "$BEFORE" | wc -l | tr -d ' ') existing tables"

for pass in 1 2; do
  echo
  echo "Applying apply-38.sql as one paste — pass ${pass}…"
  psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$BUNDLE" >/dev/null
  echo "  applied cleanly"
done

AFTER="$(fingerprint)"
echo
if [ "$BEFORE" != "$AFTER" ]; then
  echo "FAIL: applying 38 changed existing data:" >&2
  diff <(echo "$BEFORE") <(echo "$AFTER") >&2 || true
  exit 1
fi
echo "ok  no existing row in any table changed"

echo
echo "Checking the result…"
psql -v ON_ERROR_STOP=1 -v helpers="$HERE/_helpers.sql" -q -d "$DB" <<'SQL'
\i :helpers
SET lia.uid = 'b0000000-0000-0000-0000-000000000001';   -- Batavia's office
DO $$
DECLARE v_nate uuid; v json;
BEGIN
  SELECT account_id INTO v_nate FROM account_members WHERE user_id = 'b0000000-0000-0000-0000-000000000002';
  PERFORM start_impersonation(json_build_object('account_id', v_nate, 'reason', 'rehearsal')::jsonb);

  v := amend_fp_inspection(jsonb_build_object('inspection_id',
         (SELECT f.id FROM fp_inspections f JOIN assets a ON a.id = f.asset_id
           WHERE a.serial_raw = 'PROD-H1' AND f.is_current), 'reason', 'model', 'model', 'V-FIT'));
  PERFORM pg_temp.want('the office corrects Nate''s harness while acting as him', (v->>'account_id')::uuid, v_nate);

  v := add_inspection_office('{"serial_num":"PROD-9","work_order_id":"WO-PROD","reason":"radioed in"}'::jsonb);
  PERFORM pg_temp.want('and adds a ladder to his work order', (v->>'account_id')::uuid || '/' || (v->>'source'),
                       v_nate::text || '/office_add');
  PERFORM pg_temp.want('the work order counts it',
    (SELECT total FROM field_work_orders(false) WHERE work_order_id = 'WO-PROD'), 4);
  PERFORM pg_temp.want_error('an item already on record that day is refused',
    $q$ SELECT add_inspection_office('{"serial_num":"PROD-2","work_order_id":"WO-PROD","reason":"dup"}'::jsonb) $q$);
  PERFORM stop_impersonation();
END $$;

RESET lia.uid;
SET ROLE anon;
DO $$ BEGIN
  PERFORM pg_temp.want_error('anon cannot add', $q$ SELECT add_inspection_office('{}'::jsonb) $q$);
END $$;
RESET ROLE;
SQL

echo
echo "Rehearsal passed. Bundle: $BUNDLE ($(wc -l < "$BUNDLE" | tr -d ' ') lines)"
echo "Inspect with: psql -d $DB"
echo "Drop with:    psql -d postgres -c 'DROP DATABASE $DB;'"
