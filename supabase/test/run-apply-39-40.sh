#!/usr/bin/env bash
# Rehearses the LIVE apply of 39 (placeholder serials refused) and 40
# (destroyed ladders on the certificate) on a database built to look like
# production — 01–38, umbrella-shaped, field ladders under Nate, one of them
# already billed with PMCD4, and a placeholder item left over from before 39 —
# then the bundle pasted on top, twice, the way the SQL editor runs it.
#
#   * NOTHING ALREADY THERE CHANGES. Every table is fingerprinted before and
#     after. 39 adds a function and a trigger; 40 adds a function and appends
#     columns to a view.
#   * The ladder already billed with PMCD4 reads as destroyed the moment 40 is
#     applied — no record rewritten.
#   * The leftover placeholder item is not frozen, but cannot be recorded
#     against.
#
# Writes the paste-able bundle, supabase/dist/apply-39-40.sql (generated, not
# committed).
#
#   ./supabase/test/run-apply-39-40.sh
set -euo pipefail

DB="${LIA_TEST_DB:-lia_apply3940}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
MIG="$SUPA/migrations"

for p in /opt/homebrew/opt/postgresql@16/bin /opt/homebrew/bin /usr/local/bin; do
  [ -d "$p" ] && PATH="$p:$PATH"
done

pg_isready -q || { echo "No local Postgres. Try: brew services start postgresql@16" >&2; exit 1; }

mkdir -p "$SUPA/dist"
BUNDLE="$SUPA/dist/apply-39-40.sql"
{
  cat <<'HDR'
-- ═══════════════════════════════════════════════════════════════════
-- Lia — migrations 39 and 40 as one paste:
--   39  placeholder serials (N/A, none, 0000 …) refused by the database
--   40  destroyed ladders (PMCD, PMCD1–6, TRL-3) on the public certificate
--
-- GENERATED by supabase/test/run-apply-39-40.sh, which rehearsed it against
-- a production-shaped database before writing it. Do not edit by hand.
--
-- Needs 01–38 already applied. Changes no existing row. Idempotent.
--
-- OPTIONAL, BEFORE — read-only, run on its own: items that already carry a
-- placeholder serial. They keep working for corrections and tags but can't be
-- recorded against until their serial is fixed.
--   SELECT a.kind, a.serial_raw, a.account_id, a.created_at
--     FROM assets a
--    WHERE a.serial_raw !~ '[A-Za-z0-9]'
--       OR upper(regexp_replace(a.serial_raw,'[^A-Za-z0-9]','','g')) ~ '^(0+|X+)$'
--       OR upper(regexp_replace(a.serial_raw,'[^A-Za-z0-9]','','g')) IN
--          ('NA','NONE','NIL','NULL','UNKNOWN','UNK','TBD','TBA','NOSERIAL',
--           'NOSERIALNUMBER','NOSN','NOSERIALNO','NONUMBER','NONUM','NOTAG',
--           'NOLABEL','MISSING','ILLEGIBLE','NOTLEGIBLE','UNREADABLE','BLANK',
--           'EMPTY','NOTAPPLICABLE');
--
-- Check afterwards from outside, with the publishable key:
--   GET /rest/v1/ladder_inspections_public?select=destroyed,destroy_reason,tag_label&limit=1
--        → 200 with those three columns
--   GET /rest/v1/ladder_inspections_public?select=serial_num&destroyed=is.true
--        → the destroyed ladders recorded with parts so far
--   POST /rest/v1/rpc/serial_problem  {"p_serial":"N/A"}  → 401 42501 (anon refused)
-- ═══════════════════════════════════════════════════════════════════

HDR
  cat "$MIG/39_placeholder_serials.sql"
  echo
  cat "$MIG/40_destroyed_ladders.sql"
} > "$BUNDLE"

echo "Rebuilding '$DB' at migration 38, the way production stands…"
psql -q -d postgres -c "DROP DATABASE IF EXISTS $DB;" -c "CREATE DATABASE $DB;"
run() { psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$1" >/dev/null; }

run "$HERE/00_stub_supabase.sql"
# 10 is skipped, as it was on the live database (see build-combined.sh).
for f in "$MIG"/0[1-9]_*.sql "$MIG"/1[1-9]_*.sql "$MIG"/2[0-9]_*.sql "$MIG"/3[0-8]_*.sql; do
  run "$f"
done

echo "Seeding a production-shaped umbrella…"
psql -q -v ON_ERROR_STOP=1 -d "$DB" >/dev/null <<'SQL'
INSERT INTO auth.users(id,email) VALUES
  ('b0000000-0000-0000-0000-000000000001','office@batavia.test'),
  ('b0000000-0000-0000-0000-000000000002','nate@sub.test'),
  ('b0000000-0000-0000-0000-000000000003','michael@sub.test'),
  ('b0000000-0000-0000-0000-000000000004','crew@nate.test') ON CONFLICT DO NOTHING;
DO $$
DECLARE v_umb uuid; v_nate uuid;
BEGIN
  v_umb  := create_lia_user('b0000000-0000-0000-0000-000000000001','office@batavia.test','Batavia',-1,NULL,'lead','001');
  v_nate := create_subcontractor('b0000000-0000-0000-0000-000000000002','nate@sub.test','Nate','763', v_umb);
  PERFORM create_subcontractor('b0000000-0000-0000-0000-000000000003','michael@sub.test','Michael','738', v_umb);
  PERFORM create_lia_user('b0000000-0000-0000-0000-000000000004','crew@nate.test','Crew',0, v_nate,'tech');
END $$;
SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
SELECT record_inspection('{"serial_num":"PROD-1","work_order_id":"WO-PROD","source":"field","brand":"Werner","parts":[{"name":"G13","qty":2}]}'::jsonb);
SELECT record_inspection('{"serial_num":"1135318","work_order_id":"WO-PROD","source":"field","parts":[{"name":"PMCD4","qty":1}]}'::jsonb);
SELECT record_inspection('{"serial_num":"PROD-OLD","work_order_id":"WO-PROD","source":"office"}'::jsonb);
-- The live "NA" before it was merged: a placeholder item from before 39.
SELECT record_fp_inspection(jsonb_build_object('serial_num','N/A','manufacturer','MSA','model','V-FIT',
  'checks', jsonb_build_array(jsonb_build_object('prompt','Labels?','result',true))));
SQL

# Every public table, every row, as one hash per table.
fingerprint() {
  psql -tA -v ON_ERROR_STOP=1 -d "$DB" <<'SQL'
DO $$
DECLARE r record; h text;
BEGIN
  CREATE TEMP TABLE IF NOT EXISTS _fp(tbl text PRIMARY KEY, hash text);
  TRUNCATE _fp;
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname NOT LIKE 'stock_%'
            ORDER BY 1 LOOP
    EXECUTE format('SELECT md5(coalesce(string_agg((to_jsonb(t) - %L)::text, %L ORDER BY (to_jsonb(t) - %L)::text), %L)) FROM public.%I t',
                   'mfr_serial', E'\n', 'mfr_serial', '', r.relname) INTO h;
    INSERT INTO _fp VALUES (r.relname, h);
  END LOOP;
END $$;
SELECT tbl || ' ' || hash FROM _fp ORDER BY tbl;
SQL
}

BEFORE="$(fingerprint)"
echo "  fingerprinted $(echo "$BEFORE" | wc -l | tr -d ' ') existing tables"

for pass in 1 2; do
  echo
  echo "Applying apply-39-40.sql as one paste — pass ${pass}…"
  psql -q -v ON_ERROR_STOP=1 -d "$DB" -f "$BUNDLE" >/dev/null
  echo "  applied cleanly"
done

AFTER="$(fingerprint)"
echo
if [ "$BEFORE" != "$AFTER" ]; then
  echo "FAIL: applying 39–40 changed existing data:" >&2
  diff <(echo "$BEFORE") <(echo "$AFTER") >&2 || true
  exit 1
fi
echo "ok  no existing row in any table changed"

echo
echo "Checking the result…"
psql -v ON_ERROR_STOP=1 -v helpers="$HERE/_helpers.sql" -q -d "$DB" <<'SQL'
\i :helpers
SET ROLE anon;
SELECT pg_temp.want('the ladder already billed with PMCD4 reads as destroyed — no record rewritten',
  (SELECT destroy_reason FROM ladder_inspections_public WHERE serial_num = '1135318'),
  'Cut and destroyed: repair cost prohibitive');
SELECT pg_temp.want('a repaired ladder is not',
  (SELECT destroyed FROM ladder_inspections_public WHERE serial_num = 'PROD-1'), false);
SELECT pg_temp.want('an office record with no parts is not',
  (SELECT destroyed FROM ladder_inspections_public WHERE serial_num = 'PROD-OLD'), false);
SELECT pg_temp.want('every column the live sites read is still there, in place',
  (SELECT string_agg(column_name::text, ',' ORDER BY ordinal_position) FROM information_schema.columns
    WHERE table_name = 'ladder_inspections_public' AND ordinal_position <= 21),
  'serial_num,serial_key,inspection_date,tech_name,rep_name,rep_number,verified_by,next_due_date,work_order_id,notes,brand,type,length,created_at,public_ref,version,lubricated,has_leveler,has_claw,has_vrung,certificate_url');
DO $$ BEGIN
  PERFORM pg_temp.want_error('anon cannot call serial_problem', $q$ SELECT serial_problem('N/A') $q$);
END $$;
RESET ROLE;

SET lia.uid = 'b0000000-0000-0000-0000-000000000004';
DO $$ BEGIN
  PERFORM pg_temp.want_error('a field ladder as N/A is now refused',
    $q$ SELECT record_inspection('{"serial_num":"N/A","work_order_id":"WO-PROD"}'::jsonb) $q$);
  PERFORM pg_temp.want_error('the leftover N/A item cannot be recorded against',
    $q$ SELECT record_fp_inspection(jsonb_build_object('serial_num','N/A','manufacturer','MSA','model','V-FIT',
         'checks', jsonb_build_array(jsonb_build_object('prompt','Labels?','result',true)))) $q$);
END $$;
SELECT record_inspection('{"serial_num":"PROD-3","work_order_id":"WO-PROD","source":"field"}'::jsonb);
SELECT pg_temp.want('a real serial still records', (SELECT count(*) FROM inspections WHERE serial_num = 'PROD-3')::int, 1);
SQL

echo
echo "Rehearsal passed. Bundle: $BUNDLE ($(wc -l < "$BUNDLE" | tr -d ' ') lines)"
echo "Inspect with: psql -d $DB"
echo "Drop with:    psql -d postgres -c 'DROP DATABASE $DB;'"
